CREATE TABLE IF NOT EXISTS "Programmes" (
	"Programme_ID"	TEXT,
	"Programme_Name"	TEXT NOT NULL,
	"Programme_Credits"	INTEGER,
	"Faculty_ID"	VARCHAR(10),
	PRIMARY KEY("Programme_ID")
