CREATE TABLE IF NOT EXISTS "Movements" (
	"Movement_ID"	INTEGER,
	"Lecturer_ID"	TEXT NOT NULL,
	"Start_Date"	date NOT NULL,
	"End_Date"	date NOT NULL,
	"Location"	TEXT,
	"Purpose"	TEXT,
