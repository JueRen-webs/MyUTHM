BEGIN TRANSACTION;
CREATE TABLE IF NOT EXISTS "Assessment_Components" (
	"component_id"	INTEGER,
	"component_name"	VARCHAR(100) NOT NULL,
	"component_type"	VARCHAR(100) NOT NULL,
	"weightage"	DECIMAL(5, 2) NOT NULL,
	"max_marks"	INT NOT NULL,
	PRIMARY KEY("component_id" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Assessment_Enrollments" (
	"Assessment_Enrollment_ID"	INTEGER,
	"Assessment_ID"	INTEGER NOT NULL,
	"Student_ID"	VARCHAR(50) NOT NULL,
	"Marks"	REAL,
	PRIMARY KEY("Assessment_Enrollment_ID" AUTOINCREMENT),
	UNIQUE("Assessment_ID","Student_ID"),
	FOREIGN KEY("Assessment_ID") REFERENCES "Assessments"("Assessment_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Assessment_Schedules" (
	"Schedule_ID"	INTEGER,
	"Assessment_ID"	INTEGER NOT NULL,
	"Assessment_Date"	TEXT,
	"Start_Time"	TEXT,
	"Duration"	INTEGER,
	"Quiz_Title"	TEXT,
	"Duration_Minutes"	INTEGER,
	"Instructions"	TEXT,
	"Is_Hidden"	INTEGER DEFAULT 0,
	PRIMARY KEY("Schedule_ID" AUTOINCREMENT),
	FOREIGN KEY("Assessment_ID") REFERENCES "Assessments"("Assessment_ID")
);
CREATE TABLE IF NOT EXISTS "Assessments" (
	"Assessment_ID"	INTEGER,
	"Section_ID"	INTEGER NOT NULL,
	"Component_ID"	INTEGER NOT NULL,
	PRIMARY KEY("Assessment_ID" AUTOINCREMENT),
	FOREIGN KEY("Component_ID") REFERENCES "Assessment_Components"("Component_ID") ON DELETE RESTRICT,
	FOREIGN KEY("Section_ID") REFERENCES "Sections"("Section_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Assignment_Attachments" (
	"Attachment_ID"	INTEGER,
	"Assignment_ID"	INTEGER NOT NULL,
	"File_Name"	TEXT NOT NULL,
	"File_Size"	TEXT,
	"File_URL"	TEXT,
	PRIMARY KEY("Attachment_ID" AUTOINCREMENT),
	FOREIGN KEY("Assignment_ID") REFERENCES "Assignments"("Assignment_ID")
);
CREATE TABLE IF NOT EXISTS "Assignment_Groups" (
	"Group_ID"	INTEGER,
	"Assignment_ID"	INTEGER NOT NULL,
	"Group_Number"	INTEGER NOT NULL,
	PRIMARY KEY("Group_ID" AUTOINCREMENT),
	FOREIGN KEY("Assignment_ID") REFERENCES "Assignments"("Assignment_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Assignment_Types" (
	"Assignment_Type_ID"	INTEGER,
	"Details"	TEXT,
	PRIMARY KEY("Assignment_Type_ID" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Assignments" (
	"Assignment_ID"	INTEGER,
	"Section_ID"	INTEGER,
	"Assignment_Type_ID"	INTEGER,
	"Assignment_Title"	TEXT,
	"Max_Members"	INTEGER,
	"Due_Date"	date,
	"Due_Time"	time,
	PRIMARY KEY("Assignment_ID" AUTOINCREMENT),
	FOREIGN KEY("Assignment_Type_ID") REFERENCES "Assignment_Types"("Assignment_Type_ID"),
	FOREIGN KEY("Section_ID") REFERENCES "Sections"("Section_ID")
);
CREATE TABLE IF NOT EXISTS "Attendance_Sessions" (
	"Session_ID"	INTEGER,
	"Schedule_ID"	INTEGER NOT NULL,
	"Session_Date"	DATE NOT NULL,
	"Attendance_Code"	TEXT NOT NULL UNIQUE,
	"Status"	TEXT DEFAULT 'Open' CHECK("Status" IN ('Open', 'Closed')),
	"Created_At"	DATETIME DEFAULT CURRENT_TIMESTAMP,
	"Session_Start_Time"	TEXT,
	"Session_End_Time"	TEXT,
	PRIMARY KEY("Session_ID" AUTOINCREMENT),
	FOREIGN KEY("Schedule_ID") REFERENCES "Section_Schedules"("Schedule_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Clinic_List" (
	"Clinic_ID"	INTEGER,
	"Clinic_Name"	VARCHAR(100) NOT NULL,
	"Clinic_Address"	TEXT,
	"Clinic_Phone"	VARCHAR(20),
	"Type_ID"	INTEGER,
	PRIMARY KEY("Clinic_ID" AUTOINCREMENT),
	FOREIGN KEY("Type_ID") REFERENCES "Clinic_Type"("Type_ID")
);
CREATE TABLE IF NOT EXISTS "Clinic_Type" (
	"Type_ID"	INTEGER,
	"Type_Name"	VARCHAR(50) NOT NULL,
	PRIMARY KEY("Type_ID" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Course_Attendances" (
	"Attendance_ID"	INTEGER,
	"Session_ID"	INTEGER NOT NULL,
	"Student_ID"	TEXT NOT NULL,
	"Attendance_Status"	TEXT DEFAULT 'Absent',
	"Recorded_At"	DATETIME,
	PRIMARY KEY("Attendance_ID" AUTOINCREMENT),
	UNIQUE("Session_ID","Student_ID"),
	FOREIGN KEY("Session_ID") REFERENCES "Attendance_Sessions"("Session_ID") ON DELETE CASCADE,
	FOREIGN KEY("Student_ID") REFERENCES "Students"("Student_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Courses" (
	"Course_ID"	VARCHAR(10),
	"Course_Name"	VARCHAR(100) NOT NULL,
	"Course_Credits"	INTEGER NOT NULL,
	PRIMARY KEY("Course_ID")
);
CREATE TABLE IF NOT EXISTS "Courses_Enrollments" (
	"Course_Enrollment_ID"	INTEGER,
	"Section_ID"	INTEGER NOT NULL,
	"Student_ID"	VARCHAR(50) NOT NULL,
	PRIMARY KEY("Course_Enrollment_ID" AUTOINCREMENT),
	UNIQUE("Section_ID","Student_ID"),
	FOREIGN KEY("Section_ID") REFERENCES "Sections"("Section_ID") ON DELETE CASCADE,
	FOREIGN KEY("Student_ID") REFERENCES "Students"("Student_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Faculties" (
	"Faculty_ID"	TEXT,
	"Faculty_Name"	TEXT NOT NULL,
	"Faculty_URL"	VARCHAR(255),
	PRIMARY KEY("Faculty_ID")
);
CREATE TABLE IF NOT EXISTS "Group_Members" (
	"Group_Member_ID"	INTEGER,
	"Group_ID"	INTEGER NOT NULL,
	"Student_ID"	VARCHAR(50) NOT NULL,
	PRIMARY KEY("Group_Member_ID" AUTOINCREMENT),
	FOREIGN KEY("Group_ID") REFERENCES "Assignment_Groups"("Group_ID") ON DELETE CASCADE,
	FOREIGN KEY("Student_ID") REFERENCES "Students"("Student_ID") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Learning_Materials" (
	"Materials_ID"	TEXT,
	"Section_ID"	TEXT,
	"Title"	TEXT,
	"Size"	REAL,
	"Uploaded_Date"	TEXT,
	"URL"	TEXT,
	PRIMARY KEY("Materials_ID"),
	FOREIGN KEY("Section_ID") REFERENCES "Sections"("Section_ID")
);
CREATE TABLE IF NOT EXISTS "Leave_Types" (
	"Leave_Type_ID"	INTEGER,
	"Leave_Name"	TEXT NOT NULL,
	PRIMARY KEY("Leave_Type_ID" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Leaves_Records" (
	"Record_ID"	INTEGER,
	"Lecturer_ID"	TEXT NOT NULL,
	"Leave_Type_ID"	INTEGER NOT NULL,
	"Available_Leave"	INTEGER,
	"Leave_Taken"	INTEGER,
	"Start_Date"	date NOT NULL,
	"End_Date"	date NOT NULL,
	"Note"	TEXT,
	"Status"	TEXT DEFAULT 'Approved',
	PRIMARY KEY("Record_ID" AUTOINCREMENT),
	FOREIGN KEY("Leave_Type_ID") REFERENCES "Leave_Types"("Leave_Type_ID"),
	FOREIGN KEY("Lecturer_ID") REFERENCES "Lecturers"("Lecturer_ID") ON DELETE CASCADE
